#!/usr/bin/env node
// Write sitemap.xml from the real pages of ignitecuriosity.org: every tracked
// .html page reachable by links from the home page, minus what robots.txt
// disallows and the 404 page. Orphan and removed pages therefore drop out on
// their own (Curiosity-Corp/ignite-curiosity#19, decision 7).
//
//   node scripts/build-sitemap.mjs          # rewrite sitemap.xml
//   node scripts/build-sitemap.mjs --check  # exit 1 if sitemap.xml or robots.txt is out of date
//
// No <lastmod>: it would go stale on every commit and is optional in the protocol.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { posix } from 'node:path';

const ORIGIN = 'https://ignitecuriosity.org';
const SITEMAP = 'sitemap.xml';
const ROBOTS = 'robots.txt';
const SITEMAP_LINE = `Sitemap: ${ORIGIN}/${SITEMAP}`;
const EXCLUDE = new Set(['404.html']);

function read(file) {
  try {
    return readFileSync(file, 'utf8');
  } catch (err) {
    throw new Error(`cannot read ${file}: ${err.message}`);
  }
}

const tracked = new Set(execFileSync('git', ['ls-files', '*.html'], { encoding: 'utf8' }).split('\n').filter(Boolean));

// robots.txt "Disallow:" rules for "User-agent: *" ("*" wildcard, "$" end anchor).
const disallow = read(ROBOTS)
  .split('\n')
  .map((l) => l.replace(/#.*/, '').trim())
  .filter((l) => /^disallow:/i.test(l))
  .map((l) => l.slice(l.indexOf(':') + 1).trim())
  .filter(Boolean)
  .map((rule) => new RegExp('^' + rule.replace(/[.+?^${}()|[\]\\]/g, (c) => (c === '$' ? '$' : `\\${c}`)).replaceAll('*', '.*')));
const allowed = (path) => !disallow.some((re) => re.test(`/${path}`));

// Resolve one href found on `page` to a tracked page path, or null.
function resolve(page, base, href) {
  let h = href.trim();
  if (!h || h.startsWith('#') || /^(mailto|tel|javascript|data):/i.test(h)) return null;
  const abs = h.match(/^https?:\/\/(?:www\.)?ignitecuriosity\.org(\/[^?#]*)?/i);
  if (abs) h = abs[1] || '/';
  else if (/^[a-z][a-z0-9+.-]*:|^\/\//i.test(h)) return null; // another site
  h = h.replace(/[?#].*$/, '');
  try {
    h = decodeURI(h);
  } catch {
    return null; // malformed escape: not a page we can map
  }
  let path = h.startsWith('/') ? posix.normalize(h.slice(1)) : posix.normalize(posix.join(base, h));
  if (path.startsWith('..')) return null;
  if (path === '.' || path === '' || path.endsWith('/')) path = posix.join(path, 'index.html');
  else if (!path.endsWith('.html') && tracked.has(posix.join(path, 'index.html'))) path = posix.join(path, 'index.html');
  return tracked.has(path) ? path : null;
}

const seen = new Set(['index.html']);
const queue = ['index.html'];
while (queue.length) {
  const page = queue.shift();
  const src = read(page);
  const baseTag = src.match(/<base\s+href="([^"]*)"/i);
  const base = posix.normalize(posix.join(posix.dirname(page), baseTag ? baseTag[1] : '.'));
  for (const m of src.matchAll(/<a\b[^>]*?\bhref\s*=\s*["']([^"']*)["']/gi)) {
    const target = resolve(page, base, m[1]);
    if (target && !seen.has(target) && allowed(target) && !EXCLUDE.has(target)) {
      seen.add(target);
      queue.push(target);
    }
  }
}

const loc = (p) => (p === 'index.html' ? `${ORIGIN}/` : `${ORIGIN}/${p.split('/').map(encodeURIComponent).join('/')}`);
const urls = [...seen].sort((a, b) => (a === 'index.html' ? -1 : b === 'index.html' ? 1 : a.localeCompare(b)));
const xml =
  '<?xml version="1.0" encoding="UTF-8"?>\n' +
  '<!-- Generated by scripts/build-sitemap.mjs: pages reachable from the home page, minus robots.txt rules. Do not edit by hand. -->\n' +
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
  urls.map((p) => `  <url><loc>${loc(p)}</loc></url>\n`).join('') +
  '</urlset>\n';

const robots = read(ROBOTS);
const robotsOk = robots.split('\n').some((l) => l.trim() === SITEMAP_LINE);
let current = '';
try {
  current = readFileSync(SITEMAP, 'utf8');
} catch (err) {
  if (err.code !== 'ENOENT') throw new Error(`cannot read ${SITEMAP}: ${err.message}`);
}

if (process.argv.includes('--check')) {
  let bad = false;
  if (current !== xml) {
    console.error(`ERROR: ${SITEMAP} is out of date; run node scripts/build-sitemap.mjs`);
    bad = true;
  }
  if (!robotsOk) {
    console.error(`ERROR: ${ROBOTS} must carry the line "${SITEMAP_LINE}"`);
    bad = true;
  }
  if (bad) process.exit(1);
  console.log(`OK: ${SITEMAP} lists ${urls.length} pages on ${ORIGIN}; ${ROBOTS} points at it`);
} else {
  writeFileSync(SITEMAP, xml);
  console.log(`wrote ${SITEMAP}: ${urls.length} pages on ${ORIGIN}`);
  if (!robotsOk) console.error(`WARNING: ${ROBOTS} must carry the line "${SITEMAP_LINE}"`);
}
